big = 2 ** 100            # @note: 파이썬 정수는 크기 제한이 없다 — 31자리 숫자도 그냥 정수
print(big)
print(17 // 5, 17 % 5)     # @note: // 는 몫(내림), % 는 나머지
print(-17 // 5, -17 % 5)   # @note: 음수에서 // 는 아래로 내린다 → -4, 나머지는 항상 양수 쪽 → 3
print(0b1010, 0o17, 0xff)  # @note: 2진·8진·16진 표기 — 전부 같은 int 타입
print(1_000_000 + 1)       # @note: 밑줄은 자릿수 구분용, 값에 영향 없음
