s = ["a", "b", "c", "d", "e", "f"]
print(s[1:4])                 # @note: 1 이상 4 미만 — 경계 1 과 4 사이의 칸들
print(s[:3], s[3:])           # @note: 생략하면 처음부터 / 끝까지. 둘을 합치면 원본
print(s[::2], s[1::2])        # @note: step 2 — 두 칸에 하나씩
print(s[::-1])                # @note: step -1 — 거꾸로. 뒤집기 관용구
print(s[-2:], s[:-2])         # @note: 뒤에서 두 개 / 뒤 두 개를 뺀 나머지
print(s[10:20])               # @note: 범위를 벗어나도 오류가 아니라 빈 리스트 — 인덱싱과 다른 점
t = s[:]                      # @note: 전체 슬라이스 = 얕은 복사 (새 리스트 객체)
print(t is s, t == s)
